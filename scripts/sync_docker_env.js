const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const backendEnvPath = path.join(rootDir, 'backend', '.env');
const frontendEnvPath = path.join(rootDir, 'frontend', '.env.local');
const rootEnvPath = path.join(rootDir, '.env');

const envMap = new Map();

function parseEnvFile(filePath, allowOverwrite = false) {
  if (!fs.existsSync(filePath)) return;
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const match = trimmed.match(/^([A-Za-z0-9_]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      const val = match[2].trim();
      if (!envMap.has(key) || allowOverwrite) {
        envMap.set(key, val);
      }
    }
  }
}

// 1. Read existing root .env first as baseline
parseEnvFile(rootEnvPath, false);

// 2. Read active backend .env and frontend .env.local with priority
parseEnvFile(backendEnvPath, true);
parseEnvFile(frontendEnvPath, true);

// 3. Synchronize cross-service aliases & required defaults
if (envMap.has('NEXT_PUBLIC_SUPABASE_URL') && !envMap.has('SUPABASE_URL')) {
  envMap.set('SUPABASE_URL', envMap.get('NEXT_PUBLIC_SUPABASE_URL'));
}
if (envMap.has('SUPABASE_URL') && !envMap.has('NEXT_PUBLIC_SUPABASE_URL')) {
  envMap.set('NEXT_PUBLIC_SUPABASE_URL', envMap.get('SUPABASE_URL'));
}
if (envMap.has('NEXT_PUBLIC_SUPABASE_ANON_KEY') && !envMap.has('SUPABASE_ANON_KEY')) {
  envMap.set('SUPABASE_ANON_KEY', envMap.get('NEXT_PUBLIC_SUPABASE_ANON_KEY'));
}
if (envMap.has('SUPABASE_ANON_KEY') && !envMap.has('NEXT_PUBLIC_SUPABASE_ANON_KEY')) {
  envMap.set('NEXT_PUBLIC_SUPABASE_ANON_KEY', envMap.get('SUPABASE_ANON_KEY'));
}
if (envMap.has('NEXT_PUBLIC_VAPID_PUBLIC_KEY') && !envMap.has('VAPID_PUBLIC_KEY')) {
  envMap.set('VAPID_PUBLIC_KEY', envMap.get('NEXT_PUBLIC_VAPID_PUBLIC_KEY'));
}
if (envMap.has('VAPID_PUBLIC_KEY') && !envMap.has('NEXT_PUBLIC_VAPID_PUBLIC_KEY')) {
  envMap.set('NEXT_PUBLIC_VAPID_PUBLIC_KEY', envMap.get('VAPID_PUBLIC_KEY'));
}
if (envMap.has('NEXT_PUBLIC_SITE_URL') && !envMap.has('NEXT_PUBLIC_APP_URL')) {
  envMap.set('NEXT_PUBLIC_APP_URL', envMap.get('NEXT_PUBLIC_SITE_URL'));
}
if (envMap.has('NEXT_PUBLIC_APP_URL') && !envMap.has('NEXT_PUBLIC_SITE_URL')) {
  envMap.set('NEXT_PUBLIC_SITE_URL', envMap.get('NEXT_PUBLIC_APP_URL'));
}
if (!envMap.has('NEXT_PUBLIC_APP_URL')) {
  envMap.set('NEXT_PUBLIC_APP_URL', '"http://localhost:3000"');
}
if (!envMap.has('NEXT_PUBLIC_BACKEND_URL')) {
  envMap.set('NEXT_PUBLIC_BACKEND_URL', '"http://localhost:5000"');
}
if (!envMap.has('FRONTEND_URL')) {
  envMap.set('FRONTEND_URL', '"http://localhost:3000"');
}
if (!envMap.has('BACKEND_URL')) {
  envMap.set('BACKEND_URL', '"http://backend:5000"');
}

const lines = [
  '# ==============================================================================',
  '# Focentia Production Docker Environment (.env)',
  '# Auto-generated by scripts/sync_docker_env.js',
  '# =============================================================================='
];

for (const [key, val] of envMap.entries()) {
  lines.push(`${key}=${val}`);
}

fs.writeFileSync(rootEnvPath, lines.join('\n') + '\n', 'utf8');
console.log(`[sync_docker_env] Successfully synchronized ${envMap.size} variables to .env`);
